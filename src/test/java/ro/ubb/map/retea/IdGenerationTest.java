package ro.ubb.map.retea;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import ro.ubb.map.retea.domain.Utilizator;
import ro.ubb.map.retea.exceptions.RepositoryException;
import ro.ubb.map.retea.exceptions.ValidationException;
import ro.ubb.map.retea.repository.IdGenerator;
import ro.ubb.map.retea.repository.LoadWarnings;
import ro.ubb.map.retea.repository.Repository;
import ro.ubb.map.retea.repository.factory.RepositoryFactory;
import ro.ubb.map.retea.repository.file.FileRepository;
import ro.ubb.map.retea.repository.file.UtilizatorConverter;
import ro.ubb.map.retea.repository.memory.InMemoryRepository;
import ro.ubb.map.retea.validators.UtilizatorValidator;
import ro.ubb.map.retea.validators.Validator;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Properties;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/** Id generated by the repository, the demonstration name and the ';' rule of the file format. */
class IdGenerationTest {
    private static final String NUME_DEMO = "'); DROP TABLE users; --";

    private Utilizator fara(String prenume, String nume) {
        return new Utilizator(prenume, nume);
    }

    private FileRepository<Long, Utilizator> repoFisier(Path fisier) {
        return new FileRepository<>(fisier.toString(), new UtilizatorValidator(), UtilizatorConverter::fromLine,
                UtilizatorConverter::toLine, new LoadWarnings(), IdGenerator.maxPlusOne());
    }

    private List<String> linii(Path fisier) throws Exception {
        return Files.readAllLines(fisier, StandardCharsets.UTF_8);
    }

    @Test
    void inMemoryDaIdMaxPlusUnuLaPrimulSiLaUrmatorii() {
        Repository<Long, Utilizator> repo = new InMemoryRepository<>(new UtilizatorValidator(), IdGenerator.maxPlusOne());
        Utilizator a = fara("A", "A");
        Utilizator b = fara("B", "B");
        assertFalse(repo.save(a).isPresent());
        assertFalse(repo.save(b).isPresent());
        assertEquals(1L, a.getId().longValue());
        assertEquals(2L, b.getId().longValue());
    }

    @Test
    void inMemoryPastreazaIdulDatSiContinuaDupaMaxim() {
        Repository<Long, Utilizator> repo = new InMemoryRepository<>(new UtilizatorValidator(), IdGenerator.maxPlusOne());
        Utilizator cuId = fara("A", "A");
        cuId.setId(7L);
        repo.save(cuId);
        Utilizator urmator = fara("B", "B");
        repo.save(urmator);
        assertEquals(7L, cuId.getId().longValue());
        assertEquals(8L, urmator.getId().longValue());
        repo.delete(8L);
        Utilizator refolosit = fara("C", "C");
        repo.save(refolosit);
        assertEquals(8L, refolosit.getId().longValue());
    }

    @Test
    void inMemoryFaraGeneratorNuAtribuieId() {
        Repository<Long, Utilizator> repo = new InMemoryRepository<>(new UtilizatorValidator());
        Utilizator u = fara("A", "A");
        repo.save(u);
        assertEquals(null, u.getId());
    }

    @Test
    void fisierulPastreazaIdurileDinFisierSiGenereazaMaxPlusUnu(@TempDir Path dir) throws Exception {
        Path fisier = dir.resolve("u.txt");
        Files.write(fisier, "1;Ion;Pop\n5;Ana;Ene\n".getBytes(StandardCharsets.UTF_8));
        FileRepository<Long, Utilizator> repo = repoFisier(fisier);
        Utilizator nou = fara("Nou", "Nume");
        repo.save(nou);
        assertEquals(6L, nou.getId().longValue());
        assertTrue(repo.findOne(5L).isPresent());
        assertEquals(List.of("1;Ion;Pop", "5;Ana;Ene", "6;Nou;Nume"), linii(fisier));
    }

    @Test
    void fisierulGolDaPrimulId(@TempDir Path dir) {
        Utilizator nou = fara("Nou", "Nume");
        repoFisier(dir.resolve("nou.txt")).save(nou);
        assertEquals(1L, nou.getId().longValue());
    }

    @Test
    void numeCuPunctSiVirgulaInFisierDaRepositoryExceptionSiNuStricaFisierul(@TempDir Path dir) throws Exception {
        Path fisier = dir.resolve("u.txt");
        Files.write(fisier, "1;Ion;Pop\n".getBytes(StandardCharsets.UTF_8));
        FileRepository<Long, Utilizator> repo = repoFisier(fisier);
        RepositoryException e = assertThrows(RepositoryException.class, () -> repo.save(fara("Ana", NUME_DEMO)));
        assertTrue(e.getMessage().contains("nu poate fi salvat in fisier"));
        assertTrue(e.getMessage().contains(";"));
        assertEquals(List.of("1;Ion;Pop"), linii(fisier));
        // the rejected user did not stay in memory and its id is free again
        assertEquals(1, repo.stream().count());
        Utilizator ok = fara("Bun", "Nume");
        repo.save(ok);
        assertEquals(2L, ok.getId().longValue());
    }

    @Test
    void actualizareaCuPunctSiVirgulaInFisierRestaureazaVersiuneaVeche(@TempDir Path dir) throws Exception {
        Path fisier = dir.resolve("u.txt");
        Files.write(fisier, "1;Ion;Pop\n".getBytes(StandardCharsets.UTF_8));
        FileRepository<Long, Utilizator> repo = repoFisier(fisier);
        Utilizator modificat = fara("Ion", "Po;p");
        modificat.setId(1L);
        assertThrows(RepositoryException.class, () -> repo.update(modificat));
        assertEquals("Pop", repo.findOne(1L).map(Utilizator::getNume).orElse("?"));
        assertEquals(List.of("1;Ion;Pop"), linii(fisier));
    }

    @Test
    void validatorulAcceptaNumeleDeDemonstratieSiIdNull() {
        new UtilizatorValidator().validate(fara("Ana", NUME_DEMO));
    }

    @Test
    void regulaDeLungimeDinMainNuRespingeNumeleDeDemonstratie() {
        // the same rule as the lambda in Main (30 characters at most)
        Validator<Utilizator> caInMain = new UtilizatorValidator().andThen(u -> {
            if (u.getNume().trim().length() > 30) {
                throw new ValidationException("lung");
            }
        });
        assertEquals(24, NUME_DEMO.length());
        caInMain.validate(fara("Ana", NUME_DEMO));
    }

    @Test
    void factoryDaIdGeneratPentruMemorySiFile(@TempDir Path dir) {
        Stream.of("MEMORY", "FILE").forEach(tip -> {
            Properties p = new Properties();
            p.setProperty("repository.type", tip);
            p.setProperty("file.utilizatori", dir.resolve(tip + ".txt").toString());
            p.setProperty("file.prietenii", dir.resolve(tip + "p.txt").toString());
            Repository<Long, Utilizator> repo =
                    new RepositoryFactory(p, new LoadWarnings()).createUtilizatorRepository(new UtilizatorValidator());
            Utilizator u = fara("A", "B");
            repo.save(u);
            assertEquals(1L, u.getId().longValue(), tip);
        });
    }
}
