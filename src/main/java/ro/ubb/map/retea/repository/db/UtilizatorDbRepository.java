package ro.ubb.map.retea.repository.db;

import ro.ubb.map.retea.domain.Utilizator;
import ro.ubb.map.retea.exceptions.RepositoryException;
import ro.ubb.map.retea.exceptions.ValidationException;
import ro.ubb.map.retea.validators.Validator;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * PostgreSQL repository for users (table {@code users}). All the statements are
 * {@link PreparedStatement}s with {@code ?} parameters, so a name such as {@code '); DROP TABLE users; --}
 * is stored as plain text. The id is generated by the database. The optional username of a user is not
 * stored (the table has no such column) and the friends list is built by the service.
 */
public class UtilizatorDbRepository extends AbstractDbRepository<Long, Utilizator> {
    /**
     * Creates the repository; no connection is opened.
     *
     * @param validator the validator of the users
     * @param url       the database url (db.url)
     * @param user      the database user (db.user)
     * @param password  the database password (db.password)
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String user, String password) {
        super(validator, url, user, password);
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Optional<Utilizator> findOne(Long id) {
        requireNonNull(id, "Id-ul nu poate fi null.");
        try (Connection c = connect();
             PreparedStatement ps = c.prepareStatement("SELECT id, first_name, last_name FROM users WHERE id = ?")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(toUtilizator(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw wrap(e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Iterable<Utilizator> findAll() {
        List<Utilizator> utilizatori = new ArrayList<>();
        try (Connection c = connect();
             PreparedStatement ps = c.prepareStatement("SELECT id, first_name, last_name FROM users ORDER BY id");
             ResultSet rs = ps.executeQuery()) {
            // a ResultSet is a cursor, not a collection: it can only be traversed with next()
            while (rs.next()) {
                utilizatori.add(toUtilizator(rs));
            }
            return utilizatori;
        } catch (SQLException e) {
            throw wrap(e);
        }
    }

    /**
     * Saves a user. The id is generated by the database: an id already set on the entity is ignored
     * and overwritten with the generated one.
     *
     * @param entity the user to save; cannot be null
     * @return always an empty Optional (the user is saved; its id is set on {@code entity})
     * @throws IllegalArgumentException if the entity is null
     * @throws ValidationException      if the user is not valid
     * @throws RepositoryException      if the database cannot be accessed
     */
    @Override
    public Optional<Utilizator> save(Utilizator entity) {
        requireNonNull(entity, "Entitatea nu poate fi null.");
        validator.validate(entity);
        try (Connection c = connect();
             PreparedStatement ps = c.prepareStatement(
                     "INSERT INTO users(first_name, last_name) VALUES (?, ?) RETURNING id")) {
            ps.setString(1, entity.getPrenume());
            ps.setString(2, entity.getNume());
            try (ResultSet rs = ps.executeQuery()) {
                rs.next();
                entity.setId(rs.getLong(1));
            }
            return Optional.empty();
        } catch (SQLException e) {
            throw wrap(e);
        }
    }

    /**
     * {@inheritDoc}
     * The friendships of the user are removed by the service; the database cascade is only a safety net.
     *
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Optional<Utilizator> delete(Long id) {
        requireNonNull(id, "Id-ul nu poate fi null.");
        try (Connection c = connect();
             PreparedStatement ps = c.prepareStatement("DELETE FROM users WHERE id = ? RETURNING id, first_name, last_name")) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? Optional.of(toUtilizator(rs)) : Optional.empty();
            }
        } catch (SQLException e) {
            throw wrap(e);
        }
    }

    /**
     * {@inheritDoc}
     * A user without id cannot exist in the database, so it is reported as missing.
     *
     * @throws RepositoryException if the database cannot be accessed
     */
    @Override
    public Optional<Utilizator> update(Utilizator entity) {
        requireNonNull(entity, "Entitatea nu poate fi null.");
        validator.validate(entity);
        if (entity.getId() == null) {
            return Optional.of(entity);
        }
        try (Connection c = connect();
             PreparedStatement ps = c.prepareStatement(
                     "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?")) {
            ps.setString(1, entity.getPrenume());
            ps.setString(2, entity.getNume());
            ps.setLong(3, entity.getId());
            return ps.executeUpdate() == 0 ? Optional.of(entity) : Optional.empty();
        } catch (SQLException e) {
            throw wrap(e);
        }
    }

    /** The only place where a row of {@code users} becomes a {@link Utilizator}. */
    private static Utilizator toUtilizator(ResultSet rs) throws SQLException {
        Utilizator u = new Utilizator(rs.getString("first_name"), rs.getString("last_name"));
        u.setId(rs.getLong("id"));
        return u;
    }
}
